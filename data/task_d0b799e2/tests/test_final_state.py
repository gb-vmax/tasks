def read_report():
    with open(REPORT_PATH, "r") as f:
        return f.read()


# ---------------------------------------------------------------------------
# Report existence and basic properties
# ---------------------------------------------------------------------------

def test_report_file_exists():
    assert os.path.isfile(REPORT_PATH), (
        f"audit_report.txt does not exist at {REPORT_PATH}. "
        "The report must be generated by the task."
    )


def test_report_exact_content():
    actual = read_report()
    # Strip a single trailing newline if present (common with text editors)
    actual_stripped = actual.rstrip("\n")
    expected_stripped = EXPECTED_REPORT.rstrip("\n")
    assert actual_stripped == expected_stripped, (
        f"audit_report.txt content does not match expected.\n"
        f"--- EXPECTED ---\n{EXPECTED_REPORT}\n"
        f"--- ACTUAL ---\n{actual}"
    )


