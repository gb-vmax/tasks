def test_report_not_counted_in_totals():
    """audit_report.txt must not be included in byte/file counts."""
    report_size = os.stat(REPORT_PATH).st_size
    # Grand total in report is 19670; if report were included it would differ
    lines = get_report_lines()
    total_line = next((l for l in lines if l.startswith("TOTAL STORAGE USED:")), None)
    assert total_line is not None, "TOTAL STORAGE USED line not found in report"
    assert "19670" in total_line, (
        f"Grand total should be 19670 bytes (excluding audit_report.txt), "
        f"but got: '{total_line}'"
    )
    assert "12 files" in total_line, (
        f"File count should be 12 (excluding audit_report.txt), "
        f"but got: '{total_line}'"
    )


