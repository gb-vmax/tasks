def test_dotenv_file_still_intact():
    """Ensure the original .env file was not modified by the agent."""
    expected_content = (
        "APP_ENV=production\n"
        "APP_PORT=8080\n"
        "DB_HOST=db.internal\n"
        "DB_PASSWORD=supersecret123\n"
        "LOG_LEVEL=info\n"
        "SECRET_KEY=abc123xyz789\n"
    )
    assert os.path.isfile(DOTENV_PATH), (
        f"Original .env file {DOTENV_PATH} is missing."
    )
    with open(DOTENV_PATH, "r") as f:
        content = f.read()
    # Normalize: allow with or without trailing newline
    assert content.strip() == expected_content.strip(), (
        f"Original .env file {DOTENV_PATH} was modified.\n"
        f"Expected:\n{expected_content.strip()}\n\nGot:\n{content.strip()}"
    )