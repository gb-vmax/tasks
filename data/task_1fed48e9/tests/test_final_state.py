def test_report_line13_hostname():
    with open(REPORT_PATH, "r") as f:
        lines = f.read().rstrip("\n").split("\n")
    actual_hostname = os.environ.get("HOSTNAME", "")
    assert lines[12].startswith("HOSTNAME="), (
        f"Line 13 expected to start with 'HOSTNAME=' but got: {repr(lines[12])}"
    )
    reported_value = lines[12][len("HOSTNAME="):]
    # The value must match the live HOSTNAME env var
    assert reported_value == actual_hostname, (
        f"Line 13: HOSTNAME value in report is {repr(reported_value)}, "
        f"but live $HOSTNAME is {repr(actual_hostname)}."
    )


